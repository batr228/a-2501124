package com.example.report12;

public class Animal {
    private final String name;
    private final String details;
    public Animal(String name, String details) {
        this.name=name;
        this.details=details;
        
    }
    public String getName() {
        return name;
        
    }
    public String getDetails() {
        return details;
        
    }
    
}
